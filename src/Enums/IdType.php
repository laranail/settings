<?php

declare(strict_types=1);

namespace Simtabi\Laranail\Settings\Enums;

use Simtabi\Laranail\Enumerator\Attributes\Label;
use Simtabi\Laranail\Enumerator\Contracts\Enumerator;
use Simtabi\Laranail\Enumerator\Attributes\Description;
use Simtabi\Laranail\Enumerator\Concerns\HasEnumeratorBehavior;

/**
 * The key type of the package's tables and of every foreign key to them (D-5, `ids.type`).
 * Unset, it follows `laranail.db-tools.id_type`.
 */
enum IdType: string implements Enumerator
{
    use HasEnumeratorBehavior;

    #[Label('Big integer')]
    #[Description('An auto-incrementing unsigned big integer. The default.')]
    case Bigint = 'bigint';

    #[Label('UUID')]
    #[Description('A time-ordered UUID generated by the package (36 characters).')]
    case Uuid = 'uuid';

    #[Label('ULID')]
    #[Description('A ULID generated by the package (26 characters).')]
    case Ulid = 'ulid';

    /**
     * Read a configured value: these names, or laranail/db-tools' upper-case BIGINT / UUID / ULID.
     */
    public static function parse(string $value): ?self
    {
        return self::tryFrom(strtolower(trim($value)));
    }
}
